"""Line up the cheap (bounded) verdicts with the full-verifier verdicts and count disagreements.

usage: python src/analyze.py
Reads  data/candidates*.jsonl, results/cheap_*.jsonl, results/full_*.jsonl
Writes results/summary.json, results/summary.md, results/tables.tex, results/examples.md,
       results/fig_bound_curve.pdf (if matplotlib is installed)

Terms used in the output:
  wrong      the full verifier returned FALSE for the correctness query (a real violation exists)
  proved     the full verifier returned TRUE
  no answer  the full verifier timed out or returned UNKNOWN/ERROR
  accept@k   ESBMC found no violation within k loop unwindings
"""
import glob
import json
import math
from collections import Counter, defaultdict

import paths

BOUNDS = [1, 2, 5, 10, 20, 50]
HEAD = 10   # the bound Loop-R1 describes ("k < 10"); we report the whole curve as well


def wilson(x, n, z=1.96):
    if n == 0:
        return (0.0, 0.0)
    p = x / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, c - h), min(1.0, c + h))


def frac(x, n):
    lo, hi = wilson(x, n)
    return {"x": x, "n": n, "pct": round(100 * x / n, 1) if n else None,
            "lo": round(100 * lo, 1), "hi": round(100 * hi, 1)}


def show(f):
    return f"{f['x']}/{f['n']} ({f['pct']}%, 95% CI {f['lo']}-{f['hi']})" if f["n"] else "0/0"


def full_class(d):
    return {"TRUE": "proved", "FALSE": "wrong"}.get(d, "no answer")


# ---- load -------------------------------------------------------------------------------
cands = []
for p in sorted(glob.glob(str(paths.DATA / "candidates*.jsonl"))):
    cands += [json.loads(l) for l in open(p)]
full = {}
for p in sorted(glob.glob(str(paths.RESULTS / "full_*.jsonl"))):
    for l in open(p):
        r = json.loads(l)
        full[(r["instance"], r["invariant"])] = r
cheap = defaultdict(dict)
cheap_secs = defaultdict(dict)
for p in sorted(glob.glob(str(paths.RESULTS / "cheap_*.jsonl"))):
    for l in open(p):
        r = json.loads(l)
        cheap[r["cid"]][r["k"]] = r["verdict"]
        if not r.get("carried"):
            cheap_secs[r["cid"]][r["k"]] = r["seconds"]

rows = []
for c in cands:
    if not c["valid"]:
        continue
    fc = c.get("full_correct") or full.get((c["instance"], c["invariant"]), {}).get("full_correct")
    if fc is None or len(cheap.get(c["cid"], {})) < len(BOUNDS):
        continue                      # not graded by both graders yet
    tc = c.get("t_correct") or full.get((c["instance"], c["invariant"]), {}).get("t_correct")
    rows.append({**c, "full": full_class(fc), "cheap": cheap[c["cid"]], "t_full": tc})

summary = {"n_candidates_total": len(cands), "n_valid": sum(c["valid"] for c in cands),
           "n_graded_by_both": len(rows), "batches": {}}
md = ["# Results (generated by src/analyze.py)", "",
      f"Candidates: {len(cands)} sampled, {summary['n_valid']} syntactically valid, "
      f"{len(rows)} graded by both graders so far.", ""]


def block(name, rs):
    out = {"n": len(rs), "full": dict(Counter(r["full"] for r in rs)), "by_bound": {}}
    wrong = [r for r in rs if r["full"] == "wrong"]
    proved = [r for r in rs if r["full"] == "proved"]
    for k in BOUNDS:
        acc = [r for r in rs if r["cheap"][k] == "ACCEPT"]
        out["by_bound"][k] = {
            "cheap": dict(Counter(r["cheap"][k] for r in rs)),
            # of everything the cheap grader accepts, how much is definitely wrong
            "false_accept_of_accepted": frac(sum(r["full"] == "wrong" for r in acc), len(acc)),
            "accepted_no_full_answer": frac(sum(r["full"] == "no answer" for r in acc), len(acc)),
            # of the definitely wrong invariants, how many slip through the cheap grader
            "wrong_that_slip_through": frac(sum(r["cheap"][k] == "ACCEPT" for r in wrong), len(wrong)),
            # the two tools contradict each other (ESBMC counterexample vs UAutomizer proof)
            "proved_but_cheap_rejects": frac(sum(r["cheap"][k] == "REJECT" for r in proved), len(proved)),
            "proved_cheap_no_answer": frac(sum(r["cheap"][k] in ("TIMEOUT", "ERROR") for r in proved), len(proved)),
        }
    return out


def table(title, b):
    t = [f"## {title}", "",
         f"{b['n']} candidates. Full verifier: {b['full'].get('proved', 0)} proved, "
         f"{b['full'].get('wrong', 0)} wrong, {b['full'].get('no answer', 0)} no answer.", "",
         "| bound k | cheap accepts | accepted but wrong | accepted, full verifier gave no answer | wrong ones that slip through | proved but cheap rejects |",
         "|---|---|---|---|---|---|"]
    for k in BOUNDS:
        x = b["by_bound"][k]
        t.append(f"| {k} | {x['cheap'].get('ACCEPT', 0)} | {show(x['false_accept_of_accepted'])} | "
                 f"{show(x['accepted_no_full_answer'])} | {show(x['wrong_that_slip_through'])} | "
                 f"{show(x['proved_but_cheap_rejects'])} |")
    return t + [""]


uniq = {}
for r in rows:
    uniq.setdefault((r["instance"], r["invariant"]), r)
groups = {"all": rows, "distinct (loop, invariant) pairs": list(uniq.values())}
for b in sorted({r["batch"] for r in rows}):
    groups[f"batch={b}"] = [r for r in rows if r["batch"] == b]
for s in ("easy", "hard"):
    groups[f"split={s}"] = [r for r in rows if r["split"] == s]
for m in sorted({r["model"] for r in rows}):
    groups[f"model={m}"] = [r for r in rows if r["model"] == m]
for name, rs in groups.items():
    if rs:
        summary["batches"][name] = block(name, rs)
        md += table(name, summary["batches"][name])

# ---- cost of each grader ------------------------------------------------------------------
def med(xs):
    xs = sorted(xs)
    return round(xs[len(xs) // 2], 2) if xs else None


cost = {}
for s_ in ("easy", "hard"):
    rs = [r for r in rows if r["split"] == s_]
    ch = [cheap_secs[r["cid"]][HEAD] for r in rs if HEAD in cheap_secs[r["cid"]]]
    cost[s_] = {"full_median_s": med([r["t_full"] for r in rs if r["t_full"] is not None]),
                "full_no_answer": frac(sum(r["full"] == "no answer" for r in rs), len(rs)),
                "cheap_k10_median_s": med(ch),
                "cheap_k10_no_answer": frac(sum(r["cheap"][HEAD] in ("TIMEOUT", "ERROR") for r in rs), len(rs))}
summary["cost"] = cost
md += ["## Cost of each grader (correctness query only)", "",
       "| split | full verifier median s | full verifier no answer | bounded check k=10 median s | bounded check no answer |",
       "|---|---|---|---|---|"]
for s_, c_ in cost.items():
    md.append(f"| {s_} | {c_['full_median_s']} | {show(c_['full_no_answer'])} | {c_['cheap_k10_median_s']} | {show(c_['cheap_k10_no_answer'])} |")
md.append("")

# ---- does it matter: pick one of N samples with each grader --------------------------------
sel = {}
by_inst = defaultdict(list)
for r in rows:
    if r["batch"] != "single":
        by_inst[(r["batch"], r["instance"])].append(r)
for batch in sorted({b for b, _ in by_inst}):
    insts = [v for (b, _), v in by_inst.items() if b == batch]
    n = len(insts)
    first = sum(sorted(v, key=lambda r: r["sample"])[0]["full"] == "proved" for v in insts)
    oracle = sum(any(r["full"] == "proved" for r in v) for v in insts)
    res = {"n_instances": n, "first_sample_proved": frac(first, n), "any_sample_proved": frac(oracle, n), "pick_by_cheap": {}}
    for k in BOUNDS:
        hit = 0
        for v in insts:
            v = sorted(v, key=lambda r: r["sample"])
            acc = [r for r in v if r["cheap"][k] == "ACCEPT"]
            hit += (acc[0] if acc else v[0])["full"] == "proved"
        res["pick_by_cheap"][k] = frac(hit, n)
    sel[batch] = res
    md += [f"## Picking one of the samples per loop, batch {batch}", "",
           f"Loops with at least one graded sample: {n}. A pick counts as good if the full verifier proves it.", "",
           f"- take the first sample: {show(res['first_sample_proved'])}",
           *[f"- take the first sample the cheap grader accepts at k={k}: {show(res['pick_by_cheap'][k])}" for k in BOUNDS],
           f"- best possible (any sample proved): {show(res['any_sample_proved'])}", ""]
summary["selection"] = sel

# ---- examples -----------------------------------------------------------------------------
ex = ["# Wrong invariants the bounded check accepts at k=10", "",
      "Each one: the full verifier found a real violation, ESBMC found none within 10 unwindings.", ""]
inst = {i["id"]: i for i in json.load(open(paths.DATA / "instances.json"))}
slip = [r for r in rows if r["full"] == "wrong" and r["cheap"][HEAD] == "ACCEPT"]
seen = set()
for r in sorted(slip, key=lambda r: (len(inst[r["instance"]]["llm_code"]), r["cid"])):
    if (r["instance"], r["invariant"]) in seen:
        continue
    seen.add((r["instance"], r["invariant"]))
    caught = next((k for k in BOUNDS if r["cheap"][k] == "REJECT"), None)
    ex += [f"## {r['instance']}  ({r['split']}, {r['model']})", "",
           f"Candidate invariant: `{r['invariant']}`", "",
           f"Cheap verdicts by bound: {r['cheap']}. " +
           (f"First bound that catches it: {caught}." if caught else "No bound up to 50 catches it."), "",
           "```c", inst[r["instance"]]["llm_code"].strip(), "```", ""]
summary["n_distinct_slip_examples"] = len(seen)
# split the slip-throughs: programs that allocate memory behave differently (pointer comparisons)
heap = {i for i, v in inst.items() if "alloc" in v["original_program"]}
summary["slip_by_program_kind"] = {}
md += ["## Wrong invariants accepted, split by whether the program allocates memory", "",
       "| bound k | no heap: slip through | heap programs: slip through |", "|---|---|---|"]
for k in BOUNDS:
    w_no = [r for r in rows if r["full"] == "wrong" and r["instance"] not in heap]
    w_he = [r for r in rows if r["full"] == "wrong" and r["instance"] in heap]
    a = frac(sum(r["cheap"][k] == "ACCEPT" for r in w_no), len(w_no))
    b = frac(sum(r["cheap"][k] == "ACCEPT" for r in w_he), len(w_he))
    summary["slip_by_program_kind"][k] = {"no_heap": a, "heap": b}
    md.append(f"| {k} | {show(a)} | {show(b)} |")
md.append("")
summary["slip_k10_loops"] = dict(Counter(r["instance"].split("::")[0] for r in slip))
open(paths.RESULTS / "summary.md", "w").write("\n".join(md) + "\n")
contra = [r for r in rows if r["full"] == "proved" and any(v == "REJECT" for v in r["cheap"].values())]
ex += ["# Contradictions: UAutomizer proves it, ESBMC reports a violation", ""]
cseen = Counter((r["instance"], r["invariant"]) for r in contra)
for (iid, inv), n in cseen.items():
    ex += [f"- {iid}: `{inv}` ({n} samples)"]
summary["contradictions"] = {"samples": len(contra), "distinct_pairs": len(cseen),
                             "distinct_loops": len({i for i, _ in cseen})}

open(paths.RESULTS / "examples.md", "w").write("\n".join(ex) + "\n")
open(paths.RESULTS / "summary.md", "w").write("\n".join(md) + "\n")
json.dump(summary, open(paths.RESULTS / "summary.json", "w"), indent=1)

# ---- LaTeX table + figure -----------------------------------------------------------------
if "all" in summary["batches"]:
    b = summary["batches"]["all"]
    tex = ["\\begin{tabular}{rrrrr}", "\\toprule",
           "bound $k$ & accepted & accepted but wrong & 95\\% CI & wrong that slip through \\\\", "\\midrule"]
    for k in BOUNDS:
        x = b["by_bound"][k]
        fa, sl = x["false_accept_of_accepted"], x["wrong_that_slip_through"]
        tex.append(f"{k} & {fa['n']} & {fa['x']} ({fa['pct']}\\%) & {fa['lo']}--{fa['hi']}\\% & {sl['x']}/{sl['n']} ({sl['pct']}\\%) \\\\")
    tex += ["\\bottomrule", "\\end{tabular}"]
    open(paths.RESULTS / "tables.tex", "w").write("\n".join(tex) + "\n")
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        fig, ax = plt.subplots(figsize=(5, 3.2))
        for name, style in (("all", "k-o"), ("split=easy", "C0--s"), ("split=hard", "C3--^")):
            if name not in summary["batches"]:
                continue
            ys = [summary["batches"][name]["by_bound"][k]["wrong_that_slip_through"] for k in BOUNDS]
            ax.errorbar(range(len(BOUNDS)), [y["pct"] for y in ys],
                        yerr=[[y["pct"] - y["lo"] for y in ys], [y["hi"] - y["pct"] for y in ys]],
                        fmt=style, capsize=3, label=name.replace("split=", ""))
        ax.set_xticks(range(len(BOUNDS)))
        ax.set_xticklabels(BOUNDS)
        ax.set_xlabel("unwinding bound k")
        ax.set_ylabel("% of wrong invariants accepted")
        ax.legend(frameon=False)
        fig.tight_layout()
        fig.savefig(paths.RESULTS / "fig_bound_curve.pdf")
        fig.savefig(paths.RESULTS / "fig_bound_curve.png", dpi=160)
    except ImportError:
        print("matplotlib not installed; skipped figure")
print("\n".join(md[:14]))
